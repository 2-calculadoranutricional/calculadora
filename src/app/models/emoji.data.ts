export const TONOS_PIEL = ['🏻', '🏼', '🏽', '🏾', '🏿'];
export const SKIN_REGEX = /[\u{1F3FB}-\u{1F3FF}]/gu;
export const ZWJ = '\u200D';

const personaBasesList: string[] = [];
[
  ...(CATEGORIAS_EMOJIS['Emoticones y personas'] || []),
  ...(CATEGORIAS_EMOJIS['Emoticones y personas1'] || []),
  ...(CATEGORIAS_EMOJIS['Emoticones y personas2'] || []),
  ...(CATEGORIAS_EMOJIS['Emoticones y personas4'] || []),
  ...(CATEGORIAS_EMOJIS['Emoticones y personas6'] || []),
  ...(CATEGORIAS_EMOJIS['Emoticones y personas8'] || []),
  ...(CATEGORIAS_EMOJIS['Emoticones y personas11'] || []),
  ...(CATEGORIAS_EMOJIS['Actividades1'] || []),
  ...(CATEGORIAS_EMOJIS['Actividades2'] || []),
  ...(CATEGORIAS_EMOJIS['Objetos1'] || []),
  ...(CATEGORIAS_EMOJIS['Objetos3'] || []),
].forEach((item) => {
  const base = Array.isArray(item) ? item[0] : item;
  const chars = Array.from(base);
  if (chars[0]) personaBasesList.push(chars[0]);
});

export const PERSONA_BASES = new Set(personaBasesList);

export function stripSkinTones(s: string): string {
  return (s || '').replace(SKIN_REGEX, '');
}

export function soportaTonos(emoji: string): boolean {
  if (!emoji) return false;
  const clean = stripSkinTones(emoji);
  if (clean.includes(ZWJ)) {
    const partes = clean.split(ZWJ);
    return partes.some((p) => PERSONA_BASES.has(Array.from(p)[0]));
  } else {
    return PERSONA_BASES.has(Array.from(clean)[0]);
  }
}

function applyToneToPart(part: string, tone: string): string {
  if (!part) return part;
  const p = stripSkinTones(part);
  const chars = Array.from(p);
  const first = chars[0];
  if (!first) return p;
  if (PERSONA_BASES.has(first)) {
    return first + tone + chars.slice(1).join('');
  }
  return p;
}

export function aplicarTono(emoji: string, tone: string): string {
  if (!emoji) return emoji;
  const clean = stripSkinTones(emoji);
  if (clean.includes(ZWJ)) {
    return clean
      .split(ZWJ)
      .map((p) => applyToneToPart(p, tone))
      .join(ZWJ);
  } else {
    return applyToneToPart(clean, tone);
  }
}
